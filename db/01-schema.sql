-- Esquema del workshop "La memoria de tu equipo".
-- Empresa ficticia Aseguradora Los Aromos. La memoria del equipo son las
-- notas: todos los participantes comparten esta base, las leen y las corrigen.
-- Lo único con llave son los sueldos.

CREATE TABLE personas (
    persona_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre     text NOT NULL UNIQUE,
    rut        text NOT NULL UNIQUE,
    cargo      text NOT NULL,
    rol        text NOT NULL CHECK (rol IN ('Siniestros', 'Comercial', 'Personas'))
);

-- La memoria del equipo. "contenido" guarda el texto completo de la nota,
-- tal como lo escribió quien la enseñó.
CREATE TABLE notas (
    nota_id          integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo           text NOT NULL UNIQUE,                 -- A, B, C... lo asigna la base
    titulo           text NOT NULL,
    area             text NOT NULL CHECK (area IN ('Siniestros', 'Comercial', 'Personas')),
    responsable      text NOT NULL,
    contenido        text NOT NULL,
    creado_por       text NOT NULL DEFAULT 'carga inicial',
    creado_en        timestamptz NOT NULL DEFAULT now(),
    actualizado_por  text NOT NULL DEFAULT 'carga inicial',
    actualizado_en   timestamptz NOT NULL DEFAULT now()
);

-- Un título identifica una nota, sin importar mayúsculas.
CREATE UNIQUE INDEX notas_titulo_unico ON notas (lower(titulo));

-- Registro automático de cada cambio. Nadie escribe aquí a mano.
CREATE TABLE bitacora (
    bitacora_id  bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    ocurrido_en  timestamptz NOT NULL DEFAULT now(),
    usuario      text   NOT NULL,      -- participante que hizo el cambio
    tabla        text   NOT NULL,
    operacion    text   NOT NULL,      -- INSERT / UPDATE / DELETE
    fila_id      integer,
    antes        jsonb,
    despues      jsonb
);

CREATE INDEX idx_bitacora_ocurrido_en ON bitacora (ocurrido_en DESC);

-- ---------------------------------------------------------------------------
-- Tablas con llave. Los participantes no tienen ningún permiso sobre ellas:
-- solo se llega a través de las funciones de 05-acceso.sql.
-- Se cargan a mano con cargar_ficha(); sus datos no viven en este repositorio.
-- ---------------------------------------------------------------------------

CREATE TABLE credenciales (
    persona_id  integer PRIMARY KEY REFERENCES personas (persona_id),
    sal         text NOT NULL,
    clave_hash  text NOT NULL
);

CREATE TABLE sueldos (
    persona_id  integer PRIMARY KEY REFERENCES personas (persona_id),
    sueldo      text NOT NULL          -- texto: "$1.400.000 + comisiones"
);

CREATE TABLE sesiones (
    token       uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    persona_id  integer NOT NULL REFERENCES personas (persona_id),
    usuario     text NOT NULL,         -- escritorio desde el que se inició
    creada_en   timestamptz NOT NULL DEFAULT now(),
    expira_en   timestamptz NOT NULL
);

CREATE TABLE accesos (
    acceso_id    bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    ocurrido_en  timestamptz NOT NULL DEFAULT now(),
    usuario      text NOT NULL,
    rut          text NOT NULL,        -- normalizado: solo dígitos y K
    resultado    text NOT NULL CHECK (resultado IN ('ok', 'fallo'))
);

CREATE INDEX idx_accesos_ocurrido_en ON accesos (ocurrido_en DESC);
