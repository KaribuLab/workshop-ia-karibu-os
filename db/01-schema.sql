-- Esquema del workshop IA Karibu OS: una empresa ficticia que gestiona su
-- trabajo con equipos, proyectos, compromisos y riesgos.
-- Todos los participantes comparten esta base y pueden modificarla.

CREATE TABLE equipos (
    equipo_id  integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre     text NOT NULL UNIQUE,
    proposito  text NOT NULL
);

CREATE TABLE personas (
    persona_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre     text    NOT NULL,
    email      text    NOT NULL UNIQUE,
    rol        text    NOT NULL,
    equipo_id  integer NOT NULL REFERENCES equipos (equipo_id),
    activo     boolean NOT NULL DEFAULT true
);

CREATE TABLE proyectos (
    proyecto_id            integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre                 text    NOT NULL UNIQUE,
    cliente                text    NOT NULL,
    equipo_id              integer NOT NULL REFERENCES equipos (equipo_id),
    responsable_id         integer NOT NULL REFERENCES personas (persona_id),
    estado                 text    NOT NULL DEFAULT 'Planificado'
        CHECK (estado IN ('Planificado', 'En curso', 'En riesgo', 'Pausado', 'Cerrado')),
    fecha_inicio           date    NOT NULL,
    fecha_fin_planificada  date    NOT NULL,
    avance_pct             integer NOT NULL DEFAULT 0 CHECK (avance_pct BETWEEN 0 AND 100),
    CHECK (fecha_fin_planificada >= fecha_inicio)
);

CREATE TABLE compromisos (
    compromiso_id     integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    proyecto_id       integer NOT NULL REFERENCES proyectos (proyecto_id),
    descripcion       text    NOT NULL,
    responsable_id    integer REFERENCES personas (persona_id),   -- puede estar sin asignar
    estado            text    NOT NULL DEFAULT 'Pendiente'
        CHECK (estado IN ('Pendiente', 'En curso', 'Cumplido', 'Cancelado')),
    fecha_compromiso  date    NOT NULL,
    fecha_cierre      date,                                       -- solo si Cumplido o Cancelado
    creado_en         timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE riesgos (
    riesgo_id        integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    proyecto_id      integer NOT NULL REFERENCES proyectos (proyecto_id),
    descripcion      text    NOT NULL,
    severidad        text    NOT NULL
        CHECK (severidad IN ('Baja', 'Media', 'Alta', 'Crítica')),
    estado           text    NOT NULL DEFAULT 'Abierto'
        CHECK (estado IN ('Abierto', 'Mitigando', 'Cerrado')),
    dueno_id         integer REFERENCES personas (persona_id),    -- puede estar sin dueño
    plan_mitigacion  text,
    creado_en        timestamptz NOT NULL DEFAULT now()
);

-- Registro automático de cada cambio. Nadie escribe aquí a mano.
CREATE TABLE bitacora (
    bitacora_id  bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    ocurrido_en  timestamptz NOT NULL DEFAULT now(),
    usuario      text   NOT NULL,      -- participante que hizo el cambio
    tabla        text   NOT NULL,
    operacion    text   NOT NULL,      -- INSERT / UPDATE / DELETE
    fila_id      integer,
    antes        jsonb,
    despues      jsonb
);

CREATE INDEX idx_personas_equipo        ON personas (equipo_id);
CREATE INDEX idx_proyectos_equipo       ON proyectos (equipo_id);
CREATE INDEX idx_compromisos_proyecto   ON compromisos (proyecto_id);
CREATE INDEX idx_compromisos_fecha      ON compromisos (fecha_compromiso);
CREATE INDEX idx_riesgos_proyecto       ON riesgos (proyecto_id);
CREATE INDEX idx_bitacora_ocurrido_en   ON bitacora (ocurrido_en DESC);
